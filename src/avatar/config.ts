/** A personalised 3D model generated by an avatar provider (e.g. Avaturn) and stored in Supabase. */
export interface AvatarModelRef {
  provider: string;
  avatarId: string;
  /** path inside the avatar-models bucket: <user_id>/<file>.glb */
  path: string;
  gender?: Gender;
  bodyId?: string;
  /** cache-buster so replacements reload everywhere */
  v: number;
}

export interface AvatarConfig {
  gender: Gender;
  skin: string;
  faceShape: FaceShape;
  eyes: EyeStyle;
  eyeColor: string;
  brows: BrowStyle;
  nose: NoseStyle;
  mouth: MouthStyle;
  lipColor: string;
  blush: boolean;
  facialHair: FacialHair;
  hair: HairStyle;
  hairColor: string;
  top: TopStyle;
  topColor: string;
  accentColor: string;
  bottom: BottomStyle;
  bottomColor: string;
  shoes: ShoeStyle;
  shoeColor: string;
  height: number; // 0.9 – 1.1
  build: Build;
  accessories: Accessory[];
  /** when set, this personalised GLB is shown instead of the procedural character */
  model?: AvatarModelRef | null;
}

